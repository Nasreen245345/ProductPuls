/**
 * Mock feedback, each with a nested `analysis` object — mirrors what
 * GET /api/v1/feedback would return once the backend joins Feedback to
 * Feedback Analysis. `analysis: null` means AI processing hasn't run yet
 * (see Feedback Analysis Flow, Chapter 6 §11 — raw feedback is always
 * saved before analysis, so this state is expected, not an error).
 */

const MODEL = { name: 'GPT-5.5', version: '2026-01-14', promptVersion: 'v3' }

function analysis({
  pain_point,
  feature_request,
  category,
  sentiment,
  urgency,
  summary,
  status = 'success',
  confidence = 0.9,
  processingMs = 1200,
  error = null,
  analyzedAt,
}) {
  return {
    pain_point,
    feature_request,
    category,
    sentiment,
    urgency,
    summary,
    model_name: MODEL.name,
    model_version: MODEL.version,
    prompt_version: MODEL.promptVersion,
    confidence_score: confidence,
    processing_time_ms: processingMs,
    analysis_status: status,
    error_message: error,
    analyzed_at: analyzedAt,
  }
}

